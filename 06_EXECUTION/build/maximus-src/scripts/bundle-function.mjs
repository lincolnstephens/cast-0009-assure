/**
 * Bundle the API into a single file for the Netlify function.
 *
 * Why this exists. The API needs Netlify Blobs to read with strong consistency,
 * otherwise the operator and the client portal can see different answers: a
 * setting saved on one side and still stale on the other. Only a v2 function is
 * given the uncached edge URL that strong consistency requires. But a v2
 * function is packaged by Netlify's file-tracing bundler, which cannot resolve
 * this repository's pnpm workspace packages, so the function fails at run time
 * with a missing dependency.
 *
 * Bundling the server ourselves settles both: the function imports one file
 * with nothing left to resolve, so the file tracer has nothing to get wrong,
 * and the function stays v2 and reads strongly.
 *
 * Usage: node scripts/bundle-function.mjs
 */

import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");

await build({
  entryPoints: [path.join(root, "packages/server/src/app.ts")],
  outfile: path.join(root, "netlify/functions/_api-bundle.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  // Node's own modules stay external; everything else is inlined.
  external: ["node:*"],
  logLevel: "warning",
  // The server imports its own files with an explicit .ts extension.
  resolveExtensions: [".ts", ".mts", ".js", ".mjs", ".json"],
  loader: { ".ts": "ts" },
  banner: {
    js: "// Generated by scripts/bundle-function.mjs. Do not edit by hand.",
  },
});

console.log("Bundled the API to netlify/functions/_api-bundle.mjs");
